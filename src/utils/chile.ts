export function getRegiones(): string[] {
  return UBICACIONES_CHILE.map((u) => u.region);
}

export function getCiudadesPorRegion(regionName?: string | null): string[] {
  if (!regionName) return [];
  const normalized = regionName.trim().toLowerCase();
  const match = UBICACIONES_CHILE.find(
    (u) =>
      u.region.toLowerCase() === normalized ||
      u.region.toLowerCase().includes(normalized) ||
      normalized.includes(u.region.toLowerCase()),
  );
  return match ? match.ciudades : [];
}

